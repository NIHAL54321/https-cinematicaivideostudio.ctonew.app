const STOP = new Set(STOPWORDS);

/** Minimum characters in a content token. */
export const MIN_TOKEN_LENGTH = 3;
/** The longest phrase the extractor forms. */
export const MAX_PHRASE_TOKENS = 3;
/** How many source spans are kept per phrase (the occurrence COUNT is never truncated). */
export const MAX_SPANS_PER_PHRASE = 8;
/** How many keywords each bucket may hold. */
export const BUCKET_LIMITS = { primary: 3, secondary: 8, longTail: 8, semantic: 8, related: 8 } as const;

export type KeywordKind = keyof typeof BUCKET_LIMITS;

export interface KeywordRecord {
  /** Stable within the package: `kw-<kind>-<n>`. */
  id: string;
  kind: KeywordKind;
  text: string;
  tokenCount: number;
  /** How many times this exact phrase occurs in this project's own text. */
  occurrences: number;
  /** Σ weights of the fields those occurrences sit in. See SOURCE_WEIGHT_FORMULA. */
  sourceWeight: number;
  /** Every keyword's characters come from a source span; lower-cased. */
  textOrigin: "source_verbatim";
  rule: "R-KW-GRAMS";
  sources: SourceRef[];
  /** True when more occurrences existed than the ${MAX_SPANS_PER_PHRASE} spans kept. */
  spansTruncated: boolean;
  note?: string;
}

export interface KeywordBucket {
  id: KeywordKind;
  label: string;
  rule: "R-KW-BUCKETS" | "R-KW-SEMANTIC";
  keywords: KeywordRecord[];
  /** Why the bucket is empty, when it is. Never null-without-reason. */
  reason: string | null;
}

export interface KeywordPlan {
  kind: "keywords";
  rule: "R-KW-DOCUMENTS";
  weightRule: "R-KW-WEIGHT";
  tokenRule: "R-KW-TOKEN";
  stopwordRule: "R-KW-STOPWORDS";
  gramRule: "R-KW-GRAMS";
  bucketRule: "R-KW-BUCKETS";
  semanticRule: "R-KW-SEMANTIC";
  noMarketDataRule: "R-KW-NO-MARKET-DATA";
  sourceWeightFormula: string;
  /** How the primary list was chosen, stated rather than implied. */
  primaryBasis: "title_present" | "text_frequency";
  stopwordCount: number;
  corpus: {
    documents: number;
    documentsByRole: Record<DocumentWeightRole, number>;
    tokens: number;
    contentTokens: number;
    distinctPhrases: number;
  };
  buckets: KeywordBucket[];
  keywords: KeywordRecord[];
  countsByKind: Record<KeywordKind, number>;
  totalKeywords: number;
  /** The honest declaration: what market data does not exist and was not used. */
  absentData: typeof ABSENT_MARKET_DATA;
  notes: string[];
}

/* ------------------------------------------------------------------ */
/* Tokenising                                                          */
/* ------------------------------------------------------------------ */

interface Token {
  text: string;
  raw: string;
  start: number;
  end: number;
}

/** Tokens of letters/digits/apostrophes, lower-cased, with their character spans. */
export function tokenize(text: string): Token[] {
  const out: Token[] = [];
  const re = /[A-Za-z0-9]+(?:['\u2019][A-Za-z]+)*/g;
  let match = re.exec(text);
  while (match !== null) {
    out.push({
      text: match[0].toLowerCase(),
      raw: match[0],
      start: match.index,
      end: match.index + match[0].length,
    });
    match = re.exec(text);
  }
  return out;
}

function isContentToken(token: Token): boolean {
  return !STOP.has(token.text) && token.text.replace(/[^a-z0-9]/g, "").length >= MIN_TOKEN_LENGTH;
}

/** True when only whitespace/markup separates two tokens (same sentence, same run). */
function sameRun(text: string, prev: Token, next: Token): boolean {
  const gap = text.slice(prev.end, next.start);
  return !/[.!?;\n\r:—–|/]/.test(gap);
}

export interface CandidatePhrase {
  text: string;
  tokenCount: number;
  occurrences: number;
  sourceWeight: number;
  sources: SourceRef[];
  truncated: boolean;
}

interface Doc {
  ref: SourceRef;
  role: DocumentWeightRole;
  text: string;
}

/* ------------------------------------------------------------------ */
/* The corpus — this project's own stored text, one doc per field      */
/* ------------------------------------------------------------------ */

function buildDocuments(source: PublishingSource): { docs: Doc[]; skipped: string[] } {
  const docs: Doc[] = [];
  const skipped: string[] = [];
  const { project, settings, script, chapters } = source;

  const push = (
    kind: SourceRef["kind"],
    id: string,
    path: string,
    text: string | null | undefined,
    role: DocumentWeightRole,
  ): void => {
    const value = typeof text === "string" ? text.trim() : "";
    if (!value) return;
    docs.push({ ref: { kind, id, path }, role, text: value });
  };

  push("project", project.id, "title", project.title, "title");
  push("project", project.id, "description", project.description, "summary");
  if (script) {
    push("script", script.id, "title", script.title, "title");
    push("script", script.id, "logline", script.logline, "summary");
    push("script", script.id, "tone", script.tone, "body");
    push("script", script.id, "targetAudience", script.targetAudience, "body");
  }
  if (settings) {
    push("project_settings", project.id, "tone", settings.tone, "body");
    push("project_settings", project.id, "style", settings.style, "body");
    push("project_settings", project.id, "targetAudience", settings.targetAudience, "body");
  }
  for (const chapter of chapters) {
    push("chapter", chapter.id, "title", chapter.title, "heading");
    push("chapter", chapter.id, "summary", chapter.summary, "summary");
    for (const scene of chapter.scenes) {
      push("scene", scene.id, "title", scene.title, "heading");
      push("scene", scene.id, "narration", scene.narration, "body");
    }
  }
  if (docs.length === 0) {
    skipped.push(
      "No stored text exists on this project (title, description, script, chapter or scene), so there is no corpus to extract keywords from.",
    );
  }
  return { docs, skipped };
}

/** Candidate phrases of 1..3 content tokens, with occurrence counts and spans. */
function extractCandidates(docs: readonly Doc[]): {
  phrases: Map<string, CandidatePhrase>;
  tokenCount: number;
  contentTokens: number;
} {
  const phrases = new Map<string, CandidatePhrase>();
  let tokenCount = 0;
  let contentTokens = 0;

  for (const doc of docs) {
    const tokens = tokenize(doc.text);
    tokenCount += tokens.length;
    const weight = DOCUMENT_WEIGHTS[doc.role];

    // Maximal runs of adjacent content tokens (never across a stopword or a
    // sentence boundary) — the only place a phrase may be formed.
    const runs: Token[][] = [];
    let run: Token[] = [];
    for (const token of tokens) {
      if (!isContentToken(token)) {
        if (run.length > 0) runs.push(run);
        run = [];
        continue;
      }
      contentTokens += 1;
      const prev = run[run.length - 1];
      if (prev && !sameRun(doc.text, prev, token)) {
        runs.push(run);
        run = [token];
        continue;
      }
      run.push(token);
    }
    if (run.length > 0) runs.push(run);

    for (const group of runs) {
      for (let len = 1; len <= MAX_PHRASE_TOKENS; len += 1) {
        for (let i = 0; i + len <= group.length; i += 1) {
          const window = group.slice(i, i + len);
          const text = window.map((t) => t.text).join(" ");
          const span = { start: window[0].start, end: window[window.length - 1].end };
          const existing = phrases.get(text);
          const source: SourceRef = { ...doc.ref, span };
          if (existing) {
            existing.occurrences += 1;
            existing.sourceWeight += weight;
            if (existing.sources.length < MAX_SPANS_PER_PHRASE) existing.sources.push(source);
            else existing.truncated = true;
          } else {
            phrases.set(text, {
              text,
              tokenCount: len,
              occurrences: 1,
              sourceWeight: weight,
              sources: [source],
              truncated: false,
            });
          }
        }
      }
    }
  }
  return { phrases, tokenCount, contentTokens };
}

/** Descending sourceWeight, then occurrences, then alphabetical — fully deterministic. */
function byWeight(a: CandidatePhrase, b: CandidatePhrase): number {
  if (b.sourceWeight !== a.sourceWeight) return b.sourceWeight - a.sourceWeight;
  if (b.occurrences !== a.occurrences) return b.occurrences - a.occurrences;
  return a.text.localeCompare(b.text);
}

/* ------------------------------------------------------------------ */
/* The plan                                                            */
/* ------------------------------------------------------------------ */

export function buildKeywordPlan(source: PublishingSource): KeywordPlan {
  const { docs, skipped } = buildDocuments(source);
  const { phrases, tokenCount, contentTokens } = extractCandidates(docs);
  const notes: string[] = [...skipped];

  const all = [...phrases.values()].sort(byWeight);
  const titleDocs = docs.filter((d) => d.role === "title");

  // Which phrases actually occur inside a title-role document.
  const inTitle = new Set<string>();
  for (const doc of titleDocs) {
    const hay = ` ${tokenize(doc.text)
      .map((t) => t.text)
      .join(" ")} `;
    for (const phrase of all) {
      // Padded, so a phrase can only match as a whole phrase and never as a
      // substring of a longer run of words.
      if (hay.includes(` ${phrase.text} `)) inTitle.add(phrase.text);
    }
  }

  const selected = new Set<string>();
  const take = (pool: readonly CandidatePhrase[], limit: number, kind: KeywordKind): CandidatePhrase[] => {
    const picked: CandidatePhrase[] = [];
    for (const phrase of pool) {
      if (picked.length >= limit) break;
      if (selected.has(phrase.text)) continue;
      selected.add(phrase.text);
      picked.push(phrase);
    }
    return picked;
  };

  const titledPool = all.filter((p) => inTitle.has(p.text));
  const primarySource = titledPool.length > 0 ? titledPool : all;
  const primaryBasis: "title_present" | "text_frequency" = titledPool.length > 0 ? "title_present" : "text_frequency";
  const primaryPhrases = take(primarySource, BUCKET_LIMITS.primary, "primary");
  const secondaryPhrases = take(all, BUCKET_LIMITS.secondary, "secondary");
  const longTailPhrases = take(
    all.filter((p) => p.tokenCount === MAX_PHRASE_TOKENS),
    BUCKET_LIMITS.longTail,
    "longTail",
  );

  // semantic: content tokens co-occurring with the top primary phrase in the
  // SAME chapter or scene — counted inside this project only.
  const topPrimary = primaryPhrases[0] ?? null;
  const semanticPhrases: CandidatePhrase[] = [];
  if (topPrimary) {
    const coOccurring = new Map<string, { phrase: CandidatePhrase; refs: SourceRef[] }>();
    const containers: { kind: "chapter" | "scene"; id: string; text: string; path: string }[] = [];
    for (const chapter of source.chapters) {
      containers.push({
        kind: "chapter",
        id: chapter.id,
        path: "title+summary",
        text: `${chapter.title} ${chapter.summary ?? ""}`,
      });
      for (const scene of chapter.scenes) {
        containers.push({
          kind: "scene",
          id: scene.id,
          path: "title+narration",
          text: `${scene.title ?? ""} ${scene.narration ?? ""}`,
        });
      }
    }
    for (const container of containers) {
      const lower = container.text.toLowerCase();
      const present = tokenize(lower)
        .map((t) => t.text)
        .join(" ");
      if (!present.includes(topPrimary.text)) continue;
      for (const token of tokenize(lower)) {
        if (!isContentToken(token)) continue;
        if (token.text === topPrimary.text) continue;
        const candidate = phrases.get(token.text);
        if (!candidate) continue;
        if (selected.has(candidate.text)) continue;
        const entry = coOccurring.get(candidate.text);
        const ref: SourceRef = { kind: container.kind, id: container.id, path: container.path };
        if (entry) {
          if (!entry.refs.some((r) => r.kind === ref.kind && r.id === ref.id)) entry.refs.push(ref);
        } else {
          coOccurring.set(candidate.text, { phrase: candidate, refs: [ref] });
        }
      }
    }
    const ranked = [...coOccurring.values()].sort((a, b) => byWeight(a.phrase, b.phrase));
    for (const entry of ranked) {
      if (semanticPhrases.length >= BUCKET_LIMITS.semantic) break;
      selected.add(entry.phrase.text);
      // Both provenances are kept: the SPANS where this word occurs in the
      // project's text, and the chapter/scene ROWS it co-occurs with the
      // primary phrase in. Neither is dropped.
      semanticPhrases.push({
        ...entry.phrase,
        sources: [...entry.phrase.sources, ...entry.refs],
      });
    }
    if (semanticPhrases.length === 0) {
      notes.push(
        `No other content word in this project's chapters or scenes co-occurs with "${topPrimary.text}", so the semantic list is empty.`,
      );
    }
  } else {
    notes.push(
      "No phrase could be extracted from this project's text, so there is nothing for a semantic list to co-occur with.",
    );
  }

  const relatedPhrases = take(all, BUCKET_LIMITS.related, "related");

  const makeRecords = (kind: KeywordKind, picked: readonly CandidatePhrase[]): KeywordRecord[] =>
    picked.map((phrase, i) => ({
      id: `kw-${kind}-${i + 1}`,
      kind,
      text: phrase.text,
      tokenCount: phrase.tokenCount,
      occurrences: phrase.occurrences,
      sourceWeight: phrase.sourceWeight,
      textOrigin: "source_verbatim" as const,
      rule: "R-KW-GRAMS" as const,
      sources: phrase.sources,
      spansTruncated: phrase.truncated,
    }));

  const buckets: KeywordBucket[] = [
    {
      id: "primary",
      label: "Primary",
      rule: "R-KW-BUCKETS",
      keywords: makeRecords("primary", primaryPhrases),
      reason:
        primaryPhrases.length > 0
          ? null
          : all.length === 0
            ? "This project stores no text, so no phrase exists to be primary."
            : "No extracted phrase occurs in the project's or script's title, so the primary list is empty rather than filled with a phrase that is not in a title.",
    },
    {
      id: "secondary",
      label: "Secondary",
      rule: "R-KW-BUCKETS",
      keywords: makeRecords("secondary", secondaryPhrases),
      reason: secondaryPhrases.length > 0 ? null : "No further phrases remain after the primary list.",
    },
    {
      id: "longTail",
      label: "Long-tail",
      rule: "R-KW-BUCKETS",
      keywords: makeRecords("longTail", longTailPhrases),
      reason:
        longTailPhrases.length > 0
          ? null
          : `This project's text contains no ${MAX_PHRASE_TOKENS}-token phrase, so the long-tail list is empty. Padding it with shorter phrases would misreport what the text says.`,
    },
    {
      id: "semantic",
      label: "Semantic",
      rule: "R-KW-SEMANTIC",
      keywords: makeRecords("semantic", semanticPhrases),
      reason:
        semanticPhrases.length > 0
          ? null
          : topPrimary
            ? `No content word co-occurs with "${topPrimary.text}" in this project's own chapters or scenes.`
            : "No primary phrase exists, so there is nothing to derive co-occurrence from.",
    },
    {
      id: "related",
      label: "Related",
      rule: "R-KW-BUCKETS",
      keywords: makeRecords("related", relatedPhrases),
      reason: relatedPhrases.length > 0 ? null : "No phrases remain after the other lists.",
    },
  ];

  const keywords = buckets.flatMap((b) => b.keywords);
  const countsByKind = {
    primary: buckets[0].keywords.length,
    secondary: buckets[1].keywords.length,
    longTail: buckets[2].keywords.length,
    semantic: buckets[3].keywords.length,
    related: buckets[4].keywords.length,
  } satisfies Record<KeywordKind, number>;

  if (primaryBasis === "text_frequency") {
    notes.push(
      "No title text exists on this project, so the primary list is the highest-weighted phrases from its own text rather than title phrases; the basis is recorded on this plan.",
    );
  }
  notes.push(
    "Buckets are named groupings of phrases extracted from this project's own text. No keyword was supplied by a keyword tool, a search API or a platform suggestion, because this product has none.",
  );

  return {
    kind: "keywords",
    rule: "R-KW-DOCUMENTS",
    weightRule: "R-KW-WEIGHT",
    tokenRule: "R-KW-TOKEN",
    stopwordRule: "R-KW-STOPWORDS",
    gramRule: "R-KW-GRAMS",
    bucketRule: "R-KW-BUCKETS",
    semanticRule: "R-KW-SEMANTIC",
    noMarketDataRule: "R-KW-NO-MARKET-DATA",
    sourceWeightFormula: SOURCE_WEIGHT_FORMULA,
    primaryBasis,
    stopwordCount: STOPWORDS.length,
    corpus: {
      documents: docs.length,
      documentsByRole: {
        title: docs.filter((d) => d.role === "title").length,
        heading: docs.filter((d) => d.role === "heading").length,
        summary: docs.filter((d) => d.role === "summary").length,
        body: docs.filter((d) => d.role === "body").length,
      },
      tokens: tokenCount,
      contentTokens,
      distinctPhrases: phrases.size,
    },
    buckets,
    keywords,
    countsByKind,
    totalKeywords: keywords.length,
    absentData: ABSENT_MARKET_DATA,
    notes,
  };
}

/** The single phrase a pinned comment / call to action may name as the topic. */
export function primaryTopicPhrase(plan: KeywordPlan, source: PublishingSource): Field<string> {
  const primary = plan.buckets.find((b) => b.id === "primary")?.keywords[0];
  if (primary) {
    return derived(primary.text, "R-KW-BUCKETS", primary.sources, {
      textOrigin: "source_verbatim",
      note: `The highest-weighted phrase in the project's own text (sourceWeight ${primary.sourceWeight} over ${primary.occurrences} occurrence(s)), used as the topic phrase.`,
    });
  }
  const title = source.project.title?.trim();
  if (title) {
    return derived(title, "R-DESC-TITLE", [{ kind: "project", id: source.project.id, path: "title" }], {
      textOrigin: "source_verbatim",
      note: "No phrase could be extracted from this project's text, so its own title is used as the topic phrase.",
    });
  }
  return emptyNoInput(
    "Neither a keyword nor a title could be derived, so no topic phrase exists to build a comment from.",
    ["stored text on this project (title, script, chapter or scene)"],
  );
}
