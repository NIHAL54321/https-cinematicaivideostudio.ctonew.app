/**
 * Phase 7 Block 1 — KEYWORDS, extracted from the project's OWN text by
 * deterministic rules. This is the single most dangerous honesty surface in
 * Phase 7.
 *
 * THE TRAP, NAMED: this product has no source of search volume, keyword
 * difficulty, competition, trend or estimated-traffic data. It never has had
 * one. So a keyword record carries exactly two numbers, and both are counts of
 * the project's own characters:
 *
 *   - `occurrences`  — how many times this exact phrase appears in this
 *                      project's stored text,
 *   - `sourceWeight` — the sum of the weights of the fields those occurrences
 *                      sit in (title 5, chapter/scene title 3, logline/summary/
 *                      topic 2, narration/metadata 1).
 *
 * `sourceWeight` measures how prominently the project uses ITS OWN WORDS. It is
 * not a market metric and the module says so in the payload
 * (`absentData.statement`), and ./audit fails the build if any metric-shaped key
 * can be found anywhere in a package.
 *
 * Every keyword carries the source span that produced it — row kind, row id,
 * field path and the character offsets inside that field's text — so any keyword
 * can be checked by looking at the characters.
 *
 * Nothing is generated by a model and nothing is fetched: the whole module is
 * pure, so the same project text yields the same keyword list on any machine.
 */
import { derived, emptyNoInput, type Field, type SourceRef } from "./provenance";
import type { PublishingSource } from "./types";

/* ------------------------------------------------------------------ */
/* The rules, as data                                                  */
/* ------------------------------------------------------------------ */

/** Where an occurrence sits, and how much that position counts. */
export const DOCUMENT_WEIGHTS = {
  title: 5,
  heading: 3,
  summary: 2,
  body: 1,
} as const;

export type DocumentWeightRole = keyof typeof DOCUMENT_WEIGHTS;

/** The stated formula for `sourceWeight`. */
export const SOURCE_WEIGHT_FORMULA =
  "sourceWeight(phrase) = Σ over the phrase's occurrences of weight(document role), where role weights are " +
  `title=${DOCUMENT_WEIGHTS.title}, chapter/scene title=${DOCUMENT_WEIGHTS.heading}, logline/summary/topic=${DOCUMENT_WEIGHTS.summary}, ` +
  `narration/other metadata=${DOCUMENT_WEIGHTS.body}. It counts THIS PROJECT'S OWN TEXT ONLY.`;

/** The declaration carried in the payload, and enforced by ./audit. */
export const ABSENT_MARKET_DATA = {
  statement:
    "This product has no source of search-volume, keyword-difficulty, competition, trend or estimated-traffic data, for these keywords or any others. " +
    "The only numbers on a keyword are counts of its occurrences in this project's own stored text and the stated source weights of those occurrences. " +
    "Nothing here may be read as a market metric, a prediction, or a promise about how anything will be received.",
  absent: [
    "search volume (any period)",
    "keyword difficulty / competition",
    "competitor or rival keyword data",
    "estimated traffic or impressions",
    "trend or popularity over time",
    "cost per click / bid estimates",
    "ranking position",
  ],
} as const;

