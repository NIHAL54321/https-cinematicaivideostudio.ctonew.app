#!/usr/bin/env bash
# ===========================================================================
# m2-music-world.sh — the BLOCK M2 proof world on top of the p7a fixture.
# ===========================================================================
#
# Run AFTER `bash scripts/fixtures/p7a-world.sh` (which creates the account and
# the nine-scene fixture project through the app's own sign-up route).
#
# This script does three things, and it writes down every one of them:
#
#   1. SHORTENS the fixture project's nine scenes to 13 s each (117 s of
#      timeline) so a delivery fits this machine's disk and time budget, and
#      clears the narration TEXT on scenes 2, 4, 6 and 8. Clearing the text is
#      what makes the ducking measurable: `buildMusicMixGraph` ducks the bed
#      only over the spans the Scene rows state narration for, so an
#      alternating narrated / unnarrated timeline produces a bed whose level
#      steps down and back up. No narration AUDIO exists either way — no
#      text-to-speech provider is wired — so nothing here claims speech.
#
#   2. GENERATES a synthetic music bed with ffmpeg (a 30 s, 440 Hz stereo tone
#      at 48 kHz) into /home/team/render-out/phase8_music_mixing/beds/, and
#      prints its byte size and SHA-256. It is 30 s against a 117 s timeline on
#      purpose: the mix must LOOP it, and the job's own row says so.
#
#   3. WRITES one Asset row (kind MUSIC) that DECLARES ITSELF a synthetic test
#      asset — `metadata.music.syntheticTestAsset: true` and the absolute
#      `syntheticSourcePath` — with its Music and LicensingMetadata sub-rows.
#      Nothing infers "synthetic"; the row states it, and the render pipeline
#      copies that declaration into the job, the master and the delivery.
#
# It never touches the catalogue selection (that is made through the app's own
# POST /api/projects/:id/music/select by the deliveries driver).
#
# ENV: DATABASE_URL (default: the .env value), M2_BED_DIR, M2_BED_SECONDS.
# ===========================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DATABASE_URL="${DATABASE_URL:-$(grep -m1 '^DATABASE_URL=' "$ROOT/.env" | cut -d= -f2- | tr -d '"')}"
PROJECT_ID="${M2_PROJECT:-p7a_fix_project}"
BED_DIR="${M2_BED_DIR:-/home/team/render-out/phase8_music_mixing/beds}"
BED_SECONDS="${M2_BED_SECONDS:-30}"
BED="$BED_DIR/m2-synthetic-tone.wav"

say()  { printf '\n== %s\n' "$*"; }
note() { printf '   %s\n' "$*"; }
psql_c() { psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -tAc "$1"; }

say "1/3  the fixture timeline: 9 scenes at 13 s, narration text on the odd scenes only"
psql_c "SELECT count(*) FROM \"Project\" WHERE id = '$PROJECT_ID'" | grep -qx 1 \
  || { echo "no project $PROJECT_ID — run scripts/fixtures/p7a-world.sh first" >&2; exit 1; }
psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -q <<SQL
UPDATE "Scene"
   SET "durationSeconds" = 13,
       narration = CASE WHEN "order" % 2 = 0 THEN NULL ELSE narration END,
       "updatedAt" = now()
 WHERE "projectId" = '$PROJECT_ID';
SQL
psql "$DATABASE_URL" -tAc "SELECT \"order\" || ' d=' || \"durationSeconds\" || 's narrationChars=' || length(coalesce(narration,'')) FROM \"Scene\" WHERE \"projectId\" = '$PROJECT_ID' ORDER BY \"order\"" | sed 's/^/   /'

say "2/3  the synthetic bed: a ${BED_SECONDS}s 440 Hz tone, generated by ffmpeg"
mkdir -p "$BED_DIR"
ffmpeg -hide_banner -loglevel error -y \
  -f lavfi -i "sine=frequency=440:sample_rate=48000:duration=${BED_SECONDS}" \
  -ac 2 -c:a pcm_s16le "$BED"
BED_BYTES=$(stat -c%s "$BED")
BED_SHA=$(sha256sum "$BED" | cut -d' ' -f1)
note "path    : $BED"
note "bytes   : $BED_BYTES"
note "sha256  : $BED_SHA"
[ "$BED_BYTES" -gt 0 ] || { echo "ffmpeg wrote a 0-byte tone" >&2; exit 1; }

say "3/3  the Asset row that declares itself a synthetic test asset"
USER_ID=$(psql_c "SELECT \"userId\" FROM \"Project\" WHERE id = '$PROJECT_ID'")
psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -q <<SQL
DELETE FROM "Asset" WHERE "projectId" = '$PROJECT_ID' AND kind = 'MUSIC';
INSERT INTO "Asset" (id, "projectId", "userId", kind, name, status, "mimeType", "sizeBytes", "durationSeconds", metadata, "createdAt", "updatedAt")
VALUES (
  'm2_synthetic_bed', '$PROJECT_ID', '$USER_ID', 'MUSIC',
  'SYNTHETIC TEST ASSET — 440 Hz tone (ffmpeg, not a catalogue track)',
  'READY', 'audio/wav', $BED_BYTES, $BED_SECONDS,
  jsonb_build_object('music', jsonb_build_object(
    'provider', 'synthetic',
    'providerTrackId', 'm2-synthetic-tone',
    'title', 'SYNTHETIC TEST ASSET — 440 Hz tone',
    'artist', NULL,
    'artistHandle', NULL,
    'durationSeconds', $BED_SECONDS,
    'genre', NULL,
    'mood', NULL,
    'licenceText', 'Synthetic test asset generated by this team with ffmpeg. Not a catalogue track; no third-party rights are involved and no licence is claimed.',
    'verdict', jsonb_build_object(
      'permitted', true,
      'reason', 'SYNTHETIC TEST ASSET: a tone this team generated with ffmpeg for BLOCK M2''s proof. No third-party rights are involved, so there is nothing for the licence gate to refuse — and this is never called music from a catalogue.',
      'basis', 'explicit',
      'attributionRequired', false,
      'licenceText', 'Synthetic test asset (ffmpeg sine tone). No licence applies and none is claimed.'
    ),
    'intendedUse', 'commercial',
    'evaluatedAt', to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    'permalink', NULL,
    'syntheticTestAsset', true,
    'syntheticSourcePath', '$BED'
  )),
  now(), now()
);
INSERT INTO "Music" (id, "assetId", provider, model, genre, mood, bpm, status)
VALUES ('m2_synthetic_bed_music', 'm2_synthetic_bed', 'synthetic', NULL, NULL, NULL, NULL, 'SUCCEEDED');
INSERT INTO "LicensingMetadata" (id, "assetId", "licenseType", source, attribution)
VALUES ('m2_synthetic_bed_licence', 'm2_synthetic_bed', 'GENERATED',
        'Studio-generated — SYNTHETIC TEST ASSET (ffmpeg sine tone)',
        'SYNTHETIC TEST ASSET generated by this team with ffmpeg; not a catalogue track and not third-party music.');
SQL
psql "$DATABASE_URL" -tAc "SELECT id || ' | ' || name || ' | synthetic=' || (metadata->'music'->>'syntheticTestAsset') || ' | source=' || (metadata->'music'->>'syntheticSourcePath') || ' | verdict.permitted=' || (metadata->'music'->'verdict'->>'permitted') FROM \"Asset\" WHERE \"projectId\" = '$PROJECT_ID' AND kind = 'MUSIC'" | sed 's/^/   /'

printf '\n== the world is ready\n'
note "project     : $PROJECT_ID"
note "bed         : $BED ($BED_BYTES B, sha256 $BED_SHA)"
note "next        : source the scenes' clips (scripts/fixtures/p8b9-source-nine.ts search/source),"
note "              then bun scripts/fixtures/m2-music-deliveries.ts"
