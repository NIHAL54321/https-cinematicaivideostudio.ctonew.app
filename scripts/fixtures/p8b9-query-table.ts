/**
 * Phase 8 block 9 — the SUBJECT QUERY, scene by scene.
 *
 * Prints the string `buildSemanticQuery` actually hands the stock providers for
 * each scene of the 9-scene fixture project, plus the ordered `subject` terms it
 * came from. Run it before and after the subject-ordering fix and the two files
 * are the before/after table in the evidence pack:
 *
 *   bun scripts/fixtures/p8b9-query-table.ts /tmp/q_before.txt
 *   bun scripts/fixtures/p8b9-query-table.ts /tmp/q_after.txt
 *
 * Nothing here is hand-written: every query comes from the real builder, reading
 * the real scene rows. `mediaType: "video"` is passed because that is what
 * `/api/media?sceneId=…&mediaType=video` passes.
 */
import { writeFileSync } from "node:fs";
import { prisma } from "@/lib/db";
import { buildSemanticQuery } from "@/lib/media/semantic";

const PROJECT = process.env.P8B9_PROJECT ?? "p7a_fix_project";
const OUT = process.argv[2] ?? "/tmp/p8b9_query_table.txt";

async function main() {
  const scenes = await prisma.scene.findMany({
    where: { projectId: PROJECT },
    orderBy: { order: "asc" },
    select: { id: true, order: true, title: true, visualPrompt: true, narration: true },
  });
  if (scenes.length === 0) throw new Error(`project ${PROJECT} has no scenes`);

  const lines: string[] = [];
  lines.push("# Phase 8 block 9 — subject query per scene");
  lines.push(`# project: ${PROJECT}`);
  lines.push("# generated by scripts/fixtures/p8b9-query-table.ts — do not hand-edit");
  lines.push("");
  for (const s of scenes) {
    const q = buildSemanticQuery({
      narration: s.narration,
      title: s.title,
      visualPrompt: s.visualPrompt,
      mediaType: "video",
    });
    lines.push(`scene ${s.order}  ${s.id}  "${s.title ?? ""}"`);
    lines.push(`  visualPrompt : ${s.visualPrompt ?? ""}`);
    lines.push(`  narration    : ${s.narration ?? ""}`);
    lines.push(`  subject      : ${q.subject.join(" ")}`);
    lines.push(`  KEYWORDS     : ${q.keywords}`);
    lines.push("");
  }
  const text = lines.join("\n");
  writeFileSync(OUT, text);
  process.stdout.write(text);
  process.stdout.write(`\nwritten to ${OUT}\n`);
}

await main();
process.exit(0);
